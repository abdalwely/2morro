async def _seed_collection(name: str, build):
    """Insert missing built-in demo documents without replacing existing data.

    On first startup, an empty collection receives the complete demo dataset.
    If a collection is only partially populated, only missing documents with
    the deterministic IDs produced by the seed builders are inserted.
    Existing documents (including user-created or edited documents) are never
    replaced, updated, or deleted by this function.

    Note: intentionally deleted built-in demo IDs will be inserted again on a
    later startup. If demo content is intentionally removed, disable/remove the
    corresponding seed definition as part of that deliberate maintenance task.
    """
    docs = build()
    if hasattr(docs, '__await__'):
        docs = await docs

    inserted = 0
    for doc in docs:
        # The seed builders use stable _id values (svc-XX, prj-XX, mdl-XX),
        # so existence checks make repeated startup runs idempotent.
        doc_id = doc.get('_id')
        if doc_id is None:
            raise ValueError(f'Seed document for collection {name!r} has no _id')
        existing = await db[name].find_one({'_id': doc_id}, {'_id': 1})
        if existing is not None:
            continue
        try:
            await db[name].insert_one(doc)
            inserted += 1
        except Exception:
            # A concurrent startup may insert the same stable ID between the
            # existence check and insert. Suppress only if that ID now exists;
            # otherwise surface the actual database error to the caller.
            if await db[name].find_one({'_id': doc_id}, {'_id': 1}) is None:
                raise

    if inserted:
        import logging
        logging.getLogger(__name__).info(
            'Seeded %s missing demo document(s) into %s', inserted, name
        )


